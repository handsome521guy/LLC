int temp_Cal(uint16_t adc)
{
  uint8_t i;
  float mos_temp;
	if(adc>NTC3950_10K[0])
		return -32768;
	else if(adc<NTC3950_10K[180])
		return 1250;
	else
		{
		for(i=0;i<180;i++)
			{
			 if(adc== NTC3950_10K[i])
			 {
				return (i-55)*10;
			 }
			 else if(adc< NTC3950_10K[i])
			 {

			 }
			 else 
			 {
			  i=i-1;
				mos_temp=NTC3950_10K[i] - adc;
				mos_temp=mos_temp*10/(NTC3950_10K[i] - NTC3950_10K[i+1]);
				mos_temp +=(i-55)*10;
				return mos_temp;
			 }			 
			}
		}
}



